"""Make a relocatable image-and-corridor replay using only existing local files."""
import argparse
import csv
import html
import json
from pathlib import Path
import re
import tempfile

from corridor_tracking.depth_corridor_replay import make_page
from corridor_tracking.depth_person_comparison import load_run
from depth_person_prototype import digest, safe_asset


def joined_frames(person_frames, coordinate_frames):
    if len(person_frames) != len(coordinate_frames):
        raise ValueError('person/image and coordinate frame counts differ')
    result = []
    for person, coordinate in zip(person_frames, coordinate_frames):
        if (int(person['frame_index']) != int(coordinate['frame_index']) or
                str(person['timestamp_ns']) != str(coordinate['timestamp_ns']) or
                abs(float(person['elapsed_s'])-float(coordinate['elapsed_s'])) > 1e-8):
            raise ValueError('person/image and coordinate timestamps differ')
        if len(person['people']) != len(coordinate['observations']):
            raise ValueError('person and coordinate observation counts differ')
        observations = []
        for source, position in zip(person['people'], coordinate['observations']):
            if source['status'] != position['depth_status'] or source.get('surface_corridor_m') != position.get('surface_corridor_m'):
                raise ValueError('person and coordinate observations differ')
            observations.append({**position, 'region_bbox_xyxy': source.get('region_bbox_xyxy')})
        result.append({'frame_index': int(person['frame_index']), 'timestamp_ns': str(person['timestamp_ns']),
                       'elapsed_s': float(person['elapsed_s']), 'review_image': person['review_image'],
                       'observations': observations})
    return result


def validate_candidate(original, candidate, original_sha256):
    proposal = candidate.get('reassignment_candidate', {})
    if proposal.get('status') != 'proposed_not_verified' or proposal.get('source_positions_sha256') != original_sha256:
        raise ValueError('candidate does not identify the original coordinates')
    if candidate.get('metadata') != original.get('metadata') or len(candidate['frames']) != len(original['frames']):
        raise ValueError('candidate metadata or frame count differs')
    target = proposal['target_id']; changed = 0
    for old, new in zip(original['frames'], candidate['frames']):
        if any(old[k] != new[k] for k in ('frame_index','timestamp_ns','elapsed_s')) or len(old['observations']) != len(new['observations']):
            raise ValueError('candidate frame timeline differs')
        for a, b in zip(old['observations'], new['observations']):
            if a == b:
                continue
            restored = dict(b)
            proposed = restored.pop('identity_assignment', None)
            original_id = restored.pop('original_track_id', 'missing')
            proposed_id = restored.get('track_id')
            restored['track_id'] = original_id
            if (restored != a or a['track_id'] is not None or a.get('surface_corridor_m') is None
                    or original_id is not None or proposed != 'proposed' or proposed_id != target):
                raise ValueError('candidate changes a value other than an unassigned identity')
            changed += 1
        ids = [o['track_id'] for o in new['observations'] if o['track_id'] is not None]
        if len(ids) != len(set(ids)):
            raise ValueError('candidate assigns one ID twice in a frame')
    if not changed:
        raise ValueError('candidate has no proposed assignments')
    return changed


def update_index(root):
    root = Path(root)
    output = root/'depth_replay_index.html'
    marker = '<meta name="depth-replay-generated" content="1">'
    if output.exists() and marker not in output.read_text(encoding='utf-8'):
        raise FileExistsError('existing replay index was not generated by this program')
    links = []
    for replay in sorted((root/'analysis').glob('g*_recording_*_*/merged/portable_*replay.html')):
        if replay.name not in ('portable_replay.html', 'portable_candidate_replay.html'):
            continue
        manifest = replay.with_name(replay.stem+'_manifest.json')
        if not manifest.is_file():
            continue
        record = json.loads(manifest.read_text(encoding='utf-8'))
        if record.get('status') != 'complete' or digest(replay) != record.get('replay_sha256'):
            continue
        relative = replay.relative_to(root).as_posix()
        label = replay.parents[1].name + (' — ID再割当て候補' if replay.name == 'portable_candidate_replay.html' else '')
        links.append(f'<li><a href="{html.escape(relative, quote=True)}">{html.escape(label)}</a></li>')
    page = ('<!doctype html><html lang="ja"><meta charset="utf-8">'+marker+
            '<title>深度と廊下座標の再生一覧</title><style>body{font:16px system-ui;margin:24px}li{margin:8px}</style>'
            '<h1>録画と廊下座標の再生一覧</h1><p>このSSD内の既存画像と人物座標を使用します。IDと校正は暫定です。</p><ul>'+
            ''.join(links)+'</ul></html>')
    with tempfile.NamedTemporaryFile('w', encoding='utf-8', dir=root, delete=False, suffix='.tmp') as f:
        f.write(page)
        temp = Path(f.name)
    temp.replace(output)
    return output


def create_replay(root, bundle, group, recording, run_id, candidate_dir=None, update_gallery=True):
    root, bundle = Path(root), Path(bundle)
    if group not in (2, 3, 4, 5) or not re.fullmatch(r'recording_\d{3}', recording) or not re.fullmatch(r'[A-Za-z0-9_]+', run_id):
        raise ValueError('invalid group, recording or run ID')
    with (bundle/'inventory.csv').open(newline='', encoding='utf-8-sig') as f:
        rows = [r for r in csv.DictReader(f) if r['group'] == str(group) and r['recording'] == recording]
    if len(rows) != 1:
        raise ValueError('recording missing or duplicated in inventory')
    row = rows[0]
    tag = f'g{group:03d}_{recording}_{run_id}'
    merged = root/'analysis'/tag/'merged'
    coordinates = root/'coordinates'/tag
    position_file, coord_manifest = coordinates/'positions.json', coordinates/'manifest.json'
    position_manifest = json.loads(coord_manifest.read_text(encoding='utf-8-sig'))
    if (position_manifest.get('status') != 'complete' or digest(position_file) != position_manifest.get('positions_sha256')
            or {x.name for x in coordinates.iterdir()} != {'positions.json', 'manifest.json'}):
        raise ValueError('coordinate files incomplete or changed')
    original = json.loads(position_file.read_text(encoding='utf-8-sig'))
    position = original
    if candidate_dir is not None:
        candidate_dir = Path(candidate_dir)
        if {x.name for x in candidate_dir.iterdir()} != {'positions.json', 'manifest.json'}:
            raise ValueError('candidate share contains unexpected files')
        candidate_manifest = json.loads((candidate_dir/'manifest.json').read_text(encoding='utf-8-sig'))
        candidate_file = candidate_dir/'positions.json'
        if (candidate_manifest.get('status') != 'proposed_not_verified' or
                candidate_manifest.get('positions_sha256') != digest(candidate_file) or
                candidate_manifest.get('source_positions_sha256') != digest(position_file)):
            raise ValueError('candidate share hash or source mismatch')
        position = json.loads(candidate_file.read_text(encoding='utf-8-sig'))
        count_changed = validate_candidate(original, position, digest(position_file))
        if candidate_manifest.get('proposed_count') != count_changed:
            raise ValueError('candidate assignment count mismatch')
        position_file = candidate_file
    meta = position['metadata']
    reference_key = 'timeline_sha256' if row.get('timeline_sha256') else 'body_manifest_sha256'
    for key in ('recording', 'source_svo_sha256', 'setup_id', 'calibration_sha256', reference_key):
        if meta.get(key) != row[key]:
            raise ValueError(f'coordinate provenance mismatch: {key}')
    if str(meta.get('group')) != str(group) or digest(merged/'manifest.json') != meta.get('person_run_manifest_sha256'):
        raise ValueError('coordinate group or image-analysis provenance differs')
    person = load_run(merged)
    if (person['metadata'].get('source_svo_sha256') != row['source_svo_sha256'] or
            person['metadata'].get('calibration_sha256') != row['calibration_sha256']):
        raise ValueError('image analysis and recording/calibration differ')
    cal_file = bundle/row['calibration']
    if digest(cal_file) != row['calibration_sha256']:
        raise ValueError('calibration file changed')
    cal = json.loads(cal_file.read_text(encoding='utf-8-sig'))
    frames = joined_frames(person['frames'], position['frames'])
    if len(frames) != int(row['frame_count']):
        raise ValueError('replay does not include the whole SVO')
    for frame in frames:
        safe_asset(merged, frame['review_image'])
    data = {'frames': frames, 'walls': {'visible': cal.get('visible_wall_Y_m'),
            'opposite': (cal.get('other_wall_inference') or {}).get('opposite_wall_Y_m_assuming_same_boundaries')},
            'reassignment_candidate': candidate_dir is not None}
    name = 'portable_candidate_replay' if candidate_dir is not None else 'portable_replay'
    page, record = merged/f'{name}.html', merged/f'{name}_manifest.json'
    if page.exists() or record.exists():
        if not (page.is_file() and record.is_file()):
            raise FileExistsError('incomplete replay already exists')
        saved = json.loads(record.read_text(encoding='utf-8'))
        if (saved.get('status') != 'complete' or saved.get('replay_sha256') != digest(page) or
                saved.get('positions_sha256') != digest(position_file) or
                saved.get('person_manifest_sha256') != digest(merged/'manifest.json')):
            raise ValueError('existing replay no longer matches its input')
    else:
        title = f'グループ{group} {recording}' + (' ID再割当て候補' if candidate_dir is not None else '')
        page.write_text(make_page(data, title), encoding='utf-8')
        saved = {'status':'complete', 'replay_sha256':digest(page), 'positions_sha256':digest(position_file),
                 'person_manifest_sha256':digest(merged/'manifest.json'), 'calibration_sha256':digest(cal_file),
                 'frame_count':len(frames), 'image_policy':'existing images beneath replay page; no image copies'}
        record.write_text(json.dumps(saved, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    if update_gallery:
        index = update_index(root)
        print(f'Portable replay: {page}\nReplay index: {index}', flush=True)
    else:
        print(f'Portable replay: {page}', flush=True)
    return page


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--local-root', type=Path, required=True)
    p.add_argument('--bundle', type=Path, required=True)
    p.add_argument('--group', type=int, choices=[2, 3, 4, 5], required=True)
    p.add_argument('--recording', required=True)
    p.add_argument('--run-id', default='20261105_01')
    p.add_argument('--candidate-dir', type=Path, help='optional coordinate-only identity candidate')
    p.add_argument('--no-update-index', action='store_true', help='avoid modifying the shared SSD replay index')
    a = p.parse_args()
    create_replay(a.local_root, a.bundle, a.group, a.recording, a.run_id, a.candidate_dir,
                  update_gallery=not a.no_update_index)


if __name__ == '__main__':
    main()
