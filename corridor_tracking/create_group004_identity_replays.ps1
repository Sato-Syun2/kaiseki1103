param(
    [string]$LocalRoot = 'G:\kaiseki1005',
    [string]$CandidateRoot = '\\tsclient\_data_experiment_data\kaiseki1103\exchange\depth_group004_identity_candidates_20261106_01'
)
$ErrorActionPreference = 'Stop'
$ViewerShare = Split-Path -Parent $PSScriptRoot
$SourceBundle = Join-Path $LocalRoot 'depth_group004_005_bundle_20261106_01'
$CoordRoot = Join-Path $LocalRoot 'coordinates'
if (-not (Test-Path -LiteralPath $CandidateRoot -PathType Container) -or -not (Test-Path -LiteralPath $CoordRoot -PathType Container)) { throw 'Candidate share or SSD coordinates folder not found.' }
$Candidates = @(Get-ChildItem -LiteralPath $CandidateRoot -Directory | Where-Object { $_.Name -match '^g004_recording_\d{3}_temporal_20261106_01$' } | Sort-Object Name)
if ($Candidates.Count -eq 0) { throw 'No group 4 identity candidates found.' }
$Links = @()
foreach ($Candidate in $Candidates) {
    if ($Candidate.Name -notmatch '^g004_recording_(\d{3})_temporal_20261106_01$') { throw 'Invalid candidate name.' }
    $Number = $Matches[1]
    $Prefix = "g004_recording_${Number}_"
    $Meta = Get-Content -LiteralPath (Join-Path $Candidate.FullName 'manifest.json') -Raw | ConvertFrom-Json
    $LocalMatches = @(Get-ChildItem -LiteralPath $CoordRoot -Directory -Filter ($Prefix + '*') | Where-Object {
        $PositionFile = Join-Path $_.FullName 'positions.json'
        (Test-Path -LiteralPath $PositionFile -PathType Leaf) -and ((Get-FileHash -LiteralPath $PositionFile -Algorithm SHA256).Hash -eq $Meta.source_positions_sha256)
    })
    if ($LocalMatches.Count -ne 1) { throw "Expected one matching SSD recording for $Number; found $($LocalMatches.Count)." }
    $RunId = $LocalMatches[0].Name.Substring($Prefix.Length)
    Write-Host "Creating candidate replay: group 4 recording_$Number, run $RunId"
    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'bootstrap_identity_viewer.ps1') -ViewerShare $ViewerShare -LocalRoot $LocalRoot -SourceBundle $SourceBundle -CandidateShare $Candidate.FullName -Group 4 -Recording "recording_$Number" -RunId $RunId
    if ($LASTEXITCODE -ne 0) { throw "Candidate replay failed for recording_$Number. Existing files are retained." }
    $Links += "<li><a href='analysis/$($LocalMatches[0].Name)/merged/portable_candidate_replay.html'>recording_$Number</a></li>"
}
$Index = Join-Path $LocalRoot 'depth_identity_candidates_group004.html'
$Marker = '<meta name="depth-identity-candidates-group004" content="1">'
if ((Test-Path -LiteralPath $Index) -and -not ((Get-Content -LiteralPath $Index -Raw) -like "*$Marker*")) { throw 'Existing candidate index is not generated by this tool; it was not overwritten.' }
$Content = '<!doctype html><meta charset="utf-8">' + $Marker + '<title>Group 4 identity candidates</title><h1>Group 4: provisional ID candidates</h1><p>These assignments are unverified. White outlines and dashed lines mark candidates.</p><ul>' + ($Links -join '') + '</ul>'
$Tmp = Join-Path $LocalRoot ('identity_candidate_index_' + [guid]::NewGuid().ToString('N') + '.tmp')
Set-Content -LiteralPath $Tmp -Value $Content -Encoding UTF8
Move-Item -LiteralPath $Tmp -Destination $Index -Force
Write-Host "Candidate replay index: $Index"
